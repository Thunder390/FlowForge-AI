// Variables
// ---------------------------------------------------------------------------

/**
 * Model judgment is trusted to add the sensitive flag, never to remove it.
 *
 * A variable the model marked sensitive stays sensitive. One it did not is
 * promoted when its id or label reads like a credential, and its default is
 * stripped, because rule 15 forbids a sensitive variable from carrying one and
 * because a default on a secret is a secret in the document.
 */
function toVariable(
  planned: WorkflowPlan["variables"][number],
  warnings: Warning[],
): Variable {
  const suspicious =
    isSecretFieldName(planned.id) || isSecretFieldName(planned.label);
  const sensitive = planned.sensitive || suspicious;

  if (sensitive && !planned.sensitive) {
    warnings.push({
      code: "variable_marked_sensitive",
      message:
        `Variable "${planned.id}" was marked sensitive because its name reads like a credential` +
        (planned.default === ""
          ? "."
          : `, and its default value was removed. A default on a secret is a secret stored in the workflow.`),
    });
  }

  return {
    id: planned.id,
    label: planned.label,
    type: planned.type as VariableType,
    required: planned.required,
    sensitive,
    ...(sensitive || planned.default === "" ? {} : { default: planned.default }),
    ...(planned.description === "" ? {} : { description: planned.description }),
  };
}

// ---------------------------------------------------------------------------
// Credentials
// ---------------------------------------------------------------------------

/**
 * One credential per integration the workflow authenticates against.
 *
 * `required_scopes` is the union across every capability using that credential,
 * so the setup guide asks for exactly the permissions the workflow needs and no
 * more. That is a real security property, not tidiness: a guide that cannot say
 * what is needed pushes people toward granting everything.
 *
 * A capability with no `auth_required`, which is every `core.*` one, produces no
 * credential and no reference on its node.
 */
function deriveCredentials(
  plan: WorkflowPlan,
  registry: Registry,
  warnings: Warning[],
): CredentialRef[] {
  const byScope = new Map<string, { auth: AuthDefinition; scopes: Set<string> }>();

  for (const node of plan.nodes) {
    const resolved = resolve(registry, node.capability);
    if (resolved?.auth === undefined) continue;

    const scope = resolved.integration.integration;
    const existing = byScope.get(scope);
    const entry = existing ?? { auth: resolved.auth, scopes: new Set<string>() };
    for (const required of resolved.capability.required_scopes ?? []) {
      entry.scopes.add(required);
    }
    if (existing === undefined) byScope.set(scope, entry);

    if (node.capability_scope !== "" && node.capability_scope !== scope) {
      warnings.push({
        code: "capability_scope_ignored",
        node_id: node.id,
        message: `Step "${node.label}" declared credential scope "${node.capability_scope}" but ${node.capability} belongs to "${scope}". The capability decides, so "${scope}" was used.`,
      });
    }
  }

  return [...byScope.entries()]
    .sort(([a], [b]) => compareStrings(a, b))
    .map(([scope, entry]) => {
      const scopes = [...entry.scopes].sort(compareStrings);
      return {
        id: `${CREDENTIAL_PREFIX}${scope}`,
        capability_scope: scope,
        auth_type: entry.auth.type,
        label: entry.auth.label,
        ...(scopes.length === 0 ? {} : { required_scopes: scopes }),
      };
    });
}

/** The integration a node authenticates against, or `undefined` when it needs none. */
function scopeOf(planned: PlanNode, registry: Registry): string | undefined {
  const resolved = resolve(registry, planned.capability);
  if (resolved?.auth === undefined) return undefined;
  return resolved.integration.integration;
}

